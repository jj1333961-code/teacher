def apply(path, mapping):
    with open(path, encoding="utf-8") as f:
        t = f.read()
    misses = []
    for k, v in mapping:
        if k in t:
            t = t.replace(k, v)
        else:
            misses.append(k)
    with open(path, "w", encoding="utf-8") as f:
        f.write(t)
    remaining = re.findall(r'.{20}ءء+.{20}', t)
    print(f"\n=== {path} ===")
    print(f"applied={len(mapping)-len(misses)} missed={len(misses)}")
    for m in misses:
        print("  MISS:", repr(m))
    print(f"remaining hamza-run contexts ({len(remaining)}):")
    for r in remaining:
        print("   >", r.replace('\n','\\n'))
    print("FFFD count:", t.count('\ufffd'))

